import { join } from "node:path";
import { loadBotApiSpec } from "../botapi";
import { ROOT } from "../paths";
import { loadTlSchema } from "../tl";
import { botApiHandlers, tlHandlers } from "./registries";

export interface Coverage {
  botapi: { implemented: number; stubs: number; total: number };
  tl: { implemented: number; stubs: number; total: number };
}

/** Write `docs/coverage.md`: which Bot API methods and TL functions have handlers. */
export async function emitCoverage(): Promise<Coverage> {
  const spec = await loadBotApiSpec();
  const schema = await loadTlSchema("telegram_api");
  const bot = new Map((await botApiHandlers(spec.methods)).map((h) => [h.item.name, h]));
  const tl = await tlHandlers(schema.functions);

  const status = (name: string) => {
    const handler = bot.get(name);
    return handler ? (handler.stub ? "stub" : "done") : "missing";
  };
  const pct = (n: number, total: number) => `${((100 * n) / total).toFixed(1)}%`;
  const done = [...bot.values()].filter((h) => !h.stub).length;
  const tlDone = tl.filter((h) => !h.stub).length;

  const sections = new Map<string, string[]>();
  for (const m of spec.methods)
    sections.set(m.section, [...(sections.get(m.section) ?? []), m.name]);

  const lines = [
    "# Coverage",
    "",
    "Generated by `bun run codegen coverage` — do not edit by hand.",
    "",
    `- **Bot API ${spec.release.version}**: ${done} of ${spec.methods.length} methods implemented (${pct(done, spec.methods.length)})`,
    `- **MTProto layer ${schema.layer}**: ${tlDone} of ${schema.functions.length} functions handled (${pct(tlDone, schema.functions.length)}); only what bots and the client need is planned`,
    "",
    "Legend: ✅ implemented · 🧩 scaffolded stub · ⬜ not yet",
    "",
    "## Bot API by section",
    "",
    "| Section | Implemented | Total |",
    "|---|---:|---:|",
    ...[...sections].map(
      ([section, names]) =>
        `| ${section} | ${names.filter((n) => status(n) === "done").length} | ${names.length} |`,
    ),
  ];
  for (const [section, names] of sections) {
    lines.push("", `### ${section}`, "");
    for (const name of names) {
      const icon = { done: "✅", stub: "🧩", missing: "⬜" }[status(name)];
      lines.push(
        `- ${icon} [\`${name}\`](https://core.telegram.org/bots/api#${name.toLowerCase()})`,
      );
    }
  }
  lines.push("", "## MTProto functions with handlers", "");
  for (const h of tl) lines.push(`- ${h.stub ? "🧩" : "✅"} \`${h.item.name}\``);

  await Bun.write(join(ROOT, "docs", "coverage.md"), `${lines.join("\n")}\n`);
  return {
    botapi: { implemented: done, stubs: bot.size - done, total: spec.methods.length },
    tl: { implemented: tlDone, stubs: tl.length - tlDone, total: schema.functions.length },
  };
}
