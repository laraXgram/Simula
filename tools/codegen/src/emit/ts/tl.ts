import { formatCombinator } from "../../tl/format";
import type { TlCombinator, TlSchema, TlType } from "../../tl/model";
import { splitName } from "../rust/naming";

const HEADER = "// @generated by tools/codegen — do not edit by hand.";

/**
 * TypeScript types for JSON-TL (the shape `simula-tl` serializes): every object carries
 * `_` with its constructor name, `long`/`bytes` are strings, unset optional fields and
 * false bit flags are absent.
 *
 * Names mirror TL exactly: constructors and functions keep their camelCase names
 * (`messageEntityBold`, `messages.sendMessage`), boxed types their PascalCase names
 * (`MessageEntity`, `messages.Chats`). TL namespaces become TS namespaces.
 */
export function emitTsTl(schema: TlSchema): string {
  const emitter = new TsTlEmitter(schema);
  return emitter.emit();
}

/** TL constructor names that TypeScript won't accept as type names (`true#3fedd339`, `null#56730bcc`). */
const RESERVED = new Set([
  "true",
  "false",
  "null",
  "void",
  "undefined",
  "never",
  "unknown",
  "any",
  "object",
]);

function tsName(local: string): string {
  return RESERVED.has(local) ? `${local}_` : local;
}

const PRIMITIVES: Record<string, string> = {
  int: "number",
  long: "long",
  double: "number",
  string: "string",
  bytes: "bytes",
  int128: "bytes",
  int256: "bytes",
  Bool: "boolean",
  true: "true",
};

class TsTlEmitter {
  /** Local names declared per namespace ("" = root). */
  private readonly declared = new Map<string, Set<string>>();
  /** Root types shadowed inside some namespace: referenced there via `$Name`. */
  private readonly aliases = new Set<string>();

  constructor(private readonly schema: TlSchema) {
    const declare = (full: string) => {
      const { ns = "", local } = splitName(full);
      (this.declared.get(ns) ?? this.declared.set(ns, new Set()).get(ns))?.add(local);
    };
    for (const c of schema.constructors) {
      declare(c.name);
      declare(resultName(c));
    }
    for (const f of schema.functions) declare(f.name);
  }

  emit(): string {
    const byNs = new Map<string, string[]>();
    const add = (ns: string, code: string) => byNs.set(ns, [...(byNs.get(ns) ?? []), code]);

    const types = new Map<string, TlCombinator[]>();
    for (const c of this.schema.constructors) {
      if (resultName(c) === "Bool") continue;
      types.set(resultName(c), [...(types.get(resultName(c)) ?? []), c]);
    }
    for (const [type, constructors] of types) {
      const { ns = "" } = splitName(type);
      for (const c of constructors) add(ns, this.iface(c, ns));
      add(
        ns,
        `/** TL type \`${type}\`. */\nexport type ${splitName(type).local} = ${constructors.map((c) => this.ref(c.name, ns)).join(" | ")};`,
      );
    }
    for (const f of this.schema.functions)
      add(splitName(f.name).ns ?? "", this.iface(f, splitName(f.name).ns ?? ""));

    const sections: string[] = [];
    for (const [ns, items] of [...byNs].sort(([a], [b]) =>
      a === "" ? -1 : b === "" ? 1 : a.localeCompare(b),
    )) {
      sections.push(
        ns === "" ? items.join("\n\n") : `export namespace ${ns} {\n${items.join("\n\n")}\n}`,
      );
    }

    const functions = this.schema.functions.map((f) => this.ref(f.name, ""));
    const methods = this.schema.functions.map(
      (f) =>
        `  ${JSON.stringify(f.name)}: { params: ${this.ref(f.name, "")}; result: ${this.result(f)} };`,
    );
    const aliases = [...this.aliases].sort().map((name) => `type $${name} = ${name};`);

    return `${HEADER}

/**
 * JSON-TL types for \`telegram_api.tl\`${this.schema.layer ? ` (layer ${this.schema.layer})` : ""}.
 */

/** TL \`long\`: a decimal string, since JavaScript numbers lose precision past 2^53. */
export type long = string;
/** TL \`bytes\`, \`int128\`, \`int256\`: base64. */
export type bytes = string;

${sections.join("\n\n")}

/** Every function, as sent: \`{ _: "messages.sendMessage", ... }\`. */
export type Function =
  | ${functions.join("\n  | ")};

/** Parameters and result of every function, keyed by name, for typed RPC clients. */
export interface Methods {
${methods.join("\n")}
}

// Root types that a namespace shadows with its own type of the same name.
${aliases.join("\n")}
`;
  }

  private iface(c: TlCombinator, ns: string): string {
    const local = splitName(c.name).local;
    const fields = c.params
      .filter((p) => p.type.kind !== "flags")
      .map((p) => {
        const optional = p.flag ? "?" : "";
        return `  ${p.name}${optional}: ${this.type(p.type, ns)};`;
      });
    return `/** \`${formatCombinator(c)}\` */\nexport interface ${tsName(local)} {\n  _: ${JSON.stringify(c.name)};\n${fields.join("\n")}\n}`;
  }

  private type(type: TlType, ns: string): string {
    switch (type.kind) {
      case "named":
        return PRIMITIVES[type.name] ?? this.ref(type.name, ns);
      case "vector":
        return `${this.wrap(this.type(type.of, ns))}[]`;
      case "generic":
        return "Function";
      case "flags":
        throw new Error("flags has no value type");
    }
  }

  private wrap(ts: string): string {
    return ts.includes(" ") ? `(${ts})` : ts;
  }

  /** Reference a TL name from inside namespace `ns`. */
  private ref(full: string, ns: string): string {
    const { ns: target = "", local: raw } = splitName(full);
    const local = tsName(raw);
    if (target === ns) return local;
    if (target !== "") return `${target}.${local}`;
    // A root type referenced from a namespace that declares the same local name.
    if (this.declared.get(ns)?.has(local)) {
      this.aliases.add(local);
      return `$${local}`;
    }
    return local;
  }

  private result(f: TlCombinator): string {
    return f.result.kind === "generic" ? "unknown" : this.type(f.result, "");
  }
}

function resultName(c: TlCombinator): string {
  if (c.result.kind !== "named") throw new Error(`${c.name}: constructor result is not named`);
  return c.result.name;
}
