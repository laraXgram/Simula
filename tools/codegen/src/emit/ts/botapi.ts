import type { BotApiSpec, Field, TypeRef } from "../../botapi/model";
import { formatTypeRef } from "../../botapi/type-expr";
import type { BotApiNames } from "../rust/botapi";
import { pascal } from "../rust/naming";

const HEADER = "// @generated by tools/codegen — do not edit by hand.";
const DOCS = "https://core.telegram.org/bots/api";

/**
 * TypeScript types for the Bot API wire format: documented constants and enums become
 * literal types, optional fields are `?`, every method gets a `<Name>Params` interface,
 * and `Methods` maps method names to params and result.
 */
export function emitTsBotApi(spec: BotApiSpec, names: BotApiNames): string {
  const out: string[] = [];
  const anonymous = new Map<string, TypeRef[]>();
  const shorthands = new Set(
    spec.types.flatMap((t) => (t.kind === "object" && t.string_shorthand ? [t.name] : [])),
  );

  const type = (ref: TypeRef): string => {
    switch (ref.kind) {
      case "primitive":
        return PRIMITIVES[ref.name];
      case "array": {
        const inner = type(ref.of);
        return `${inner.includes(" ") && !inner.endsWith("[]") ? `(${inner})` : inner}[]`;
      }
      case "ref":
        return shorthands.has(ref.name) ? `${ref.name} | string` : ref.name;
      case "union": {
        const key = formatTypeRef(ref);
        const name = names.unions[key];
        if (!name)
          throw new Error(`anonymous union "${key}" has no name in spec/botapi/names.json`);
        if (!names.builtins.includes(name)) anonymous.set(name, ref.of);
        return name;
      }
    }
  };

  const field = (f: Field): string => {
    const c = f.constraints;
    let ts: string;
    if (c?.const !== undefined) ts = JSON.stringify(c.const);
    else if (c?.enum && f.type.kind === "primitive" && f.type.name === "String")
      ts = c.enum.map((e) => JSON.stringify(e)).join(" | ");
    else ts = type(f.type);
    return `${jsdoc(f.description, "  ")}  ${f.name}${f.required ? "" : "?"}: ${ts};`;
  };

  for (const t of spec.types) {
    const header = `${jsdoc(t.description)}`;
    if (t.kind === "object") {
      const body = t.fields.map(field).join("\n");
      out.push(`${header}export interface ${t.name} {${body ? `\n${body}\n` : ""}}`);
    } else {
      out.push(`${header}export type ${t.name} = ${t.variants.map(type).join(" | ")};`);
    }
  }

  const methods: string[] = [];
  for (const m of spec.methods) {
    const name = `${pascal(m.name)}Params`;
    const body = m.params.map(field).join("\n");
    out.push(`${jsdoc(m.description)}export interface ${name} {${body ? `\n${body}\n` : ""}}`);
    methods.push(`  ${m.name}: { params: ${name}; result: ${type(m.returns)} };`);
  }

  const unions = [...anonymous].map(
    ([name, members]) =>
      `/** \`${formatTypeRef({ kind: "union", of: members })}\` in the docs. */\nexport type ${name} = ${members.map(type).join(" | ")};`,
  );

  return `${HEADER}

/** Telegram Bot API ${spec.release.version} (${spec.release.date}) wire types. */

export const BOT_API_VERSION = ${JSON.stringify(spec.release.version)};

/** \`Integer or String\`: a chat id or an \`@username\`. */
export type ChatId = number | string;
/** \`InputFile or String\`: a file_id, an HTTP(S) URL, or \`attach://<multipart field>\`. */
export type InputFile = string;

${[...out, ...unions].join("\n\n")}

/** Parameters and result of every method, keyed by name. */
export interface Methods {
${methods.join("\n")}
}
`;
}

const PRIMITIVES = {
  Integer: "number",
  Float: "number",
  String: "string",
  Boolean: "boolean",
  True: "true",
  InputFile: "InputFile",
} as const;

function jsdoc(markdown: string, indent = ""): string {
  const text = markdown
    .replace(/\[([^\]]*)\]\(#([^)]*)\)/g, `[$1](${DOCS}#$2)`)
    .replace(/\*\//g, "*\\/")
    .trim();
  if (!text) return "";
  const lines = text.split("\n").map((line) => `${indent} *${line ? ` ${line}` : ""}`);
  return `${indent}/**\n${lines.join("\n")}\n${indent} */\n`;
}
